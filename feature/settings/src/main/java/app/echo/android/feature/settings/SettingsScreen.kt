import app.echo.android.model.playback.EchoPlaybackStatus
import app.echo.android.model.playback.EchoReplayGainMode
import app.echo.android.model.settings.EchoBackgroundStyle
import app.echo.android.model.settings.EchoEffectivePerformanceMode

@Composable
fun SettingsScreen(
    isActive: Boolean = true,
    importedFontFamily: FontFamily? = null,
    status: EchoPlaybackStatus,
    trackCount: Int,
    albumCount: Int,
    artistCount: Int,
    libraryDurationMs: Long = 0L,
    librarySizeBytes: Long = 0L,
    libraryScanning: Boolean = false,
    onLoadLibraryHealth: suspend () -> app.echo.android.model.library.LibraryHealthStats = {
        app.echo.android.model.library.LibraryHealthStats()
    },
    onLoadLibraryAudioProfile: suspend () -> app.echo.android.model.library.LibraryAudioProfile = {
        app.echo.android.model.library.LibraryAudioProfile()
    },
    onInspectLibraryLyrics: suspend ((app.echo.android.model.library.LibraryLyricsInspection) -> Unit) -> Unit = {},
    appVersionLabel: String,
    updateContent: @Composable () -> Unit = {},
    dynamicArtworkEnabled: Boolean,
    compactModeEnabled: Boolean,
    playbackHapticsEnabled: Boolean,
    performanceMode: String,
    effectivePerformanceMode: String,
    trackAudioInfoTagsVisible: Boolean,
    watchedFolderRescanEnabled: Boolean,
    pcHandoffEnabled: Boolean,
    onlineLyricsEnabled: Boolean,
    lockScreenLyricsEnabled: Boolean,
    floatingLyrics: app.echo.android.model.settings.EchoFloatingLyricsSettings =
        app.echo.android.model.settings.EchoFloatingLyricsSettings(),
    floatingLyricsPermissionGranted: Boolean = false,
    lyricsOptions: app.echo.android.model.settings.EchoLyricsOptions = app.echo.android.model.settings.EchoLyricsOptions(),
    onLyricsOptionsChange: (app.echo.android.model.settings.EchoLyricsOptions) -> Unit = {},
    onOpenLyricsInterface: () -> Unit = {},
    usbExclusiveEnabled: Boolean,
    usbBitPerfectEnabled: Boolean,
    usbOutputOptions: app.echo.android.model.playback.EchoUsbOutputOptions = app.echo.android.model.playback.EchoUsbOutputOptions(),
    shuffleOptions: app.echo.android.model.playback.EchoShuffleOptions = app.echo.android.model.playback.EchoShuffleOptions(),
    trackTransitions: app.echo.android.model.playback.EchoTrackTransitionOptions,
    usbExclusiveAutoRequestOnStartup: Boolean,
    audioFocusEnabled: Boolean = true,
    onAudioFocusEnabledChange: (Boolean) -> Unit = {},
    onResetAudioOutput: () -> Unit = {},
    audioInterruptionPolicy: String = "duck",
    sleepTimerFinishTrack: Boolean = true,
    onOpenSystemAudioEffects: () -> Unit = {},
    systemEffectsLocalPlayback: Boolean = true,
    stopOnTaskRemoved: Boolean = false,
    onStopOnTaskRemovedChange: (Boolean) -> Unit = {},
    onAudioInterruptionPolicyChange: (String) -> Unit = {},
    onSleepTimerFinishTrackChange: (Boolean) -> Unit = {},
    pauseOnAudioDisconnect: Boolean,
    resumeOnAudioReconnect: Boolean,
    replayGainEnabled: Boolean,
    replayGainMode: String,
    replayGainPreampDb: Float,
    usbExclusiveTestResult: String,
    customBackgroundMode: String,
    customBackgroundUri: String?,
    startupBackgroundUri: String?,
    customBackgroundBlur: Float,
    customBackgroundBrightness: Float,
    customBackgroundGlass: Float,
    customBackgroundScale: Float,
    uiFontFamily: String,
    uiFontScale: Float,
    uiDensityScale: Float,
    lyricsFontFamily: String,
    lyricsFontScale: Float,
    importedFontUri: String?,
    themeMode: String,
    appLanguage: String,
    scheduledDarkModeEnabled: Boolean,
    scheduledDarkStartMinute: Int,
    scheduledDarkEndMinute: Int,
    lastFmEnabled: Boolean,
    lastFmApiKey: String?,
    lastFmSharedSecret: String?,
    lastFmSessionKey: String?,
    lastFmStatusLabel: String,
    lastFmErrorLabel: String?,
    lastFmWebAuthPending: Boolean,
    lastFmApiKeyLocked: Boolean,
    lastFmSharedSecretLocked: Boolean,
    listenBrainzEnabled: Boolean,
    listenBrainzToken: String?,
    listenBrainzStatusLabel: String,
    listenBrainzErrorLabel: String?,
    setlistFmApiKey: String? = null,
    setlistFmApiKeyLocked: Boolean = false,
    onDynamicArtworkEnabledChange: (Boolean) -> Unit,
    onCompactModeEnabledChange: (Boolean) -> Unit,
    onPlaybackHapticsEnabledChange: (Boolean) -> Unit,
    onPerformanceModeChange: (String) -> Unit,
    onTrackAudioInfoTagsVisibleChange: (Boolean) -> Unit,
    onWatchedFolderRescanEnabledChange: (Boolean) -> Unit,
    onPcHandoffEnabledChange: (Boolean) -> Unit,
    onOnlineLyricsEnabledChange: (Boolean) -> Unit,
    onLockScreenLyricsEnabledChange: (Boolean) -> Unit,
    onFloatingLyricsChange: (app.echo.android.model.settings.EchoFloatingLyricsSettings) -> Unit = {},
    onRequestFloatingLyricsPermission: () -> Unit = {},
    onUsbExclusiveEnabledChange: (Boolean) -> Unit,
    onUsbBitPerfectEnabledChange: (Boolean) -> Unit,
    onUsbOutputOptionsChange: (app.echo.android.model.playback.EchoUsbOutputOptions) -> Unit = {},
    onShuffleOptionsChange: (app.echo.android.model.playback.EchoShuffleOptions) -> Unit = {},
    onTrackTransitionsChange: (app.echo.android.model.playback.EchoTrackTransitionOptions) -> Unit,
    onUsbExclusiveAutoRequestOnStartupChange: (Boolean) -> Unit,
    onPauseOnAudioDisconnectChange: (Boolean) -> Unit,
    onResumeOnAudioReconnectChange: (Boolean) -> Unit,
    onReplayGainChange: (Boolean, Float) -> Unit,
    onReplayGainModeChange: (EchoReplayGainMode) -> Unit,
    onTestUsbExclusiveDriver: () -> Unit,
    onPickImageBackground: () -> Unit,
    onPickStartupBackground: () -> Unit,
    onClearStartupBackground: () -> Unit,
    onPickVideoBackground: () -> Unit,
    onClearCustomBackground: () -> Unit,
    onCustomBackgroundBlurChange: (Float) -> Unit,
    onCustomBackgroundBrightnessChange: (Float) -> Unit,
    onCustomBackgroundGlassChange: (Float) -> Unit,
    onCustomBackgroundScaleChange: (Float) -> Unit,
    onCustomBackgroundStyleChange: (EchoBackgroundStyle) -> Unit,
    onUiFontFamilyChange: (String) -> Unit,
    onUiFontScaleChange: (Float) -> Unit,
    onUiDensityScaleChange: (Float) -> Unit,
    onLyricsFontFamilyChange: (String) -> Unit,
    onLyricsFontScaleChange: (Float) -> Unit,
    onImportUiFont: () -> Unit,
    onImportLyricsFont: () -> Unit,
    onClearImportedFont: () -> Unit,
    onThemeModeChange: (String) -> Unit,
    onAppLanguageChange: (String) -> Unit,
    onScheduledDarkModeEnabledChange: (Boolean) -> Unit,
    onScheduledDarkStartMinuteChange: (Int) -> Unit,
    onScheduledDarkEndMinuteChange: (Int) -> Unit,
    onLastFmEnabledChange: (Boolean) -> Unit,
    onStartLastFmWebAuth: () -> Unit,
    onCompleteLastFmWebAuth: () -> Unit,
    onDisconnectLastFm: () -> Unit,
    onOpenLastFmApiAccounts: () -> Unit,
    onListenBrainzEnabledChange: (Boolean) -> Unit,
    onSaveListenBrainzToken: (String) -> Unit,
    onDisconnectListenBrainz: () -> Unit,
    onSaveSetlistFmApiKey: (String?) -> Unit = {},
    onOpenLibrary: () -> Unit,
    onOpenLibraryRepair: () -> Unit = {},
    onClearLocalLibraryIndex: suspend () -> Boolean,
    onCleanupLocalLibrary: suspend () -> Pair<Int, Int> = { 0 to 0 },
    errorLogCount: Int = 0,
    onOpenErrorLog: () -> Unit = {},
    backupNotice: app.echo.android.model.backup.EchoBackupNotice? = null,
    onExportBackup: () -> Unit = {},
    onImportBackup: () -> Unit = {},
    notificationPermissionGranted: Boolean = true,
    onRequestNotificationPermission: () -> Unit = {},
    onOpenPlugins: () -> Unit = {},
    isPageVisible: Boolean = isActive,
    onScanMusic: () -> Unit = onOpenLibrary,
    onOpenSound: () -> Unit = {},
    soundSummary: String = "",
    permissionState: SettingsPermissionState = SettingsPermissionState(),
    onOpenPermissionSettings: (SettingsPermissionTarget) -> Unit = {},
    lyricsMotionMode: String = EchoLyricsMotionMode.Smooth,
    onLyricsMotionModeChange: (String) -> Unit = {},
    lyricsWordHighlightEnabled: Boolean = true,
    onLyricsWordHighlightEnabledChange: (Boolean) -> Unit = {},
    accessibilityCareContent: @Composable () -> Unit = {},
) {
    SettingsNavigation(
        isActive = isActive,
        isPageVisible = isPageVisible,
        compactMode = compactModeEnabled,
        onOpenPlugins = onOpenPlugins,
        onScanMusic = onScanMusic,
        onOpenSound = onOpenSound,
        soundSummary = soundSummary,
        searchAvailability = SettingsSearchAvailability(
            scheduledDarkEnabled = scheduledDarkModeEnabled,
            customBackgroundMode = customBackgroundMode,
            backgroundAdvancedAvailable = customBackgroundMode != EchoBackgroundMode.Default &&
                !customBackgroundUri.isNullOrBlank() &&
                !(customBackgroundMode == EchoBackgroundMode.Video &&
                    effectivePerformanceMode == EchoEffectivePerformanceMode.Lightweight.id),
            trackFadeEnabled = trackTransitions.fadeEnabled,
            replayGainEnabled = replayGainEnabled,
            lastFmEnabled = lastFmEnabled,
            lastFmConnected = lastFmEnabled && !lastFmSessionKey.isNullOrBlank(),
            listenBrainzEnabled = listenBrainzEnabled,
            listenBrainzConnected = listenBrainzEnabled && !listenBrainzToken.isNullOrBlank(),
            setlistFmLocked = setlistFmApiKeyLocked,
            importedFont = !importedFontUri.isNullOrBlank(),
            notificationPermissionNeeded = app.echo.android.design.LocalEchoPlatformCapabilities.current
                .notificationRuntimePermission && !notificationPermissionGranted,
        ),
        summaries = mapOf(
            SettingsCategory.Permissions to stringResource(
                if (permissionState.needsAttention(floatingLyrics.enabled)) R.string.permissions_attention
                else R.string.permissions_ready),
            SettingsCategory.Appearance to stringResource(when (themeMode) {
                EchoThemeMode.Dark -> R.string.settings_theme_dark
                EchoThemeMode.Light -> R.string.settings_theme_light
                else -> R.string.settings_theme_system
            }),
            SettingsCategory.Interface to languageDetail(appLanguage),
            SettingsCategory.Playback to stringResource(if (usbExclusiveEnabled) R.string.settings_usb_exclusive else R.string.settings_section_lyrics),
            SettingsCategory.Usb to stringResource(status.usbOutputPresentation().headlineResource()),
            SettingsCategory.Services to (lastFmStatusLabel + " · " + listenBrainzStatusLabel),
            SettingsCategory.Library to stringResource(R.string.settings_library_summary, trackCount, albumCount, artistCount),
            SettingsCategory.About to appVersionLabel,
        ),
    ) { category, subNav ->
        when (category) {
                SettingsCategory.Permissions -> SettingsPermissionsContent(
                    permissionState, floatingLyrics.enabled, onOpenPermissionSettings,
                )
                SettingsCategory.Appearance -> SettingsAppearanceContent(
                    subNav = subNav,
                    importedFontFamily = importedFontFamily,
                    customBackgroundMode = customBackgroundMode,
                    customBackgroundUri = customBackgroundUri,
                    startupBackgroundUri = startupBackgroundUri,
                    customBackgroundBlur = customBackgroundBlur,
                    customBackgroundBrightness = customBackgroundBrightness,
                    customBackgroundGlass = customBackgroundGlass,
                    customBackgroundScale = customBackgroundScale,
                    uiFontFamily = uiFontFamily,
                    uiFontScale = uiFontScale,
                    uiDensityScale = uiDensityScale,
                    lyricsFontFamily = lyricsFontFamily,
                    lyricsFontScale = lyricsFontScale,
                    importedFontUri = importedFontUri,
                    themeMode = themeMode,
                    scheduledDarkModeEnabled = scheduledDarkModeEnabled,
                    scheduledDarkStartMinute = scheduledDarkStartMinute,
                    scheduledDarkEndMinute = scheduledDarkEndMinute,
                    onPickImageBackground = onPickImageBackground,
                    onPickStartupBackground = onPickStartupBackground,
                    onClearStartupBackground = onClearStartupBackground,
                    onPickVideoBackground = onPickVideoBackground,
                    onClearCustomBackground = onClearCustomBackground,
                    onCustomBackgroundBlurChange = onCustomBackgroundBlurChange,
                    onCustomBackgroundBrightnessChange = onCustomBackgroundBrightnessChange,
                    onCustomBackgroundGlassChange = onCustomBackgroundGlassChange,
                    onCustomBackgroundScaleChange = onCustomBackgroundScaleChange,
                    onCustomBackgroundStyleChange = onCustomBackgroundStyleChange,
                    onUiFontFamilyChange = onUiFontFamilyChange,
                    onUiFontScaleChange = onUiFontScaleChange,
                    onLyricsFontFamilyChange = onLyricsFontFamilyChange,
                    onLyricsFontScaleChange = onLyricsFontScaleChange,
                    onImportUiFont = onImportUiFont,
                    onImportLyricsFont = onImportLyricsFont,
                    onClearImportedFont = onClearImportedFont,
                    onThemeModeChange = onThemeModeChange,
                    onScheduledDarkModeEnabledChange = onScheduledDarkModeEnabledChange,
                    onScheduledDarkStartMinuteChange = onScheduledDarkStartMinuteChange,
                    onScheduledDarkEndMinuteChange = onScheduledDarkEndMinuteChange,
                )
                SettingsCategory.Accessibility -> SettingsAccessibilityContent(
                    subNav = subNav,
                    isActive = isActive && isPageVisible,
                    importedFontFamily = importedFontFamily,
                    uiFontFamily = uiFontFamily,
                    uiFontScale = uiFontScale,
                    lyricsFontFamily = lyricsFontFamily,
                    lyricsFontScale = lyricsFontScale,
                    compactModeEnabled = compactModeEnabled,
                    lyricsWordHighlightEnabled = lyricsWordHighlightEnabled,
                    lyricsMotionMode = lyricsMotionMode,
                    playbackHapticsEnabled = playbackHapticsEnabled,
                    onUiFontScaleChange = onUiFontScaleChange,
                    onLyricsFontScaleChange = onLyricsFontScaleChange,
                    onCompactModeEnabledChange = onCompactModeEnabledChange,
                    onLyricsWordHighlightEnabledChange = onLyricsWordHighlightEnabledChange,
                    careContent = accessibilityCareContent,
                    onLyricsMotionModeChange = onLyricsMotionModeChange,
                    onPlaybackHapticsEnabledChange = onPlaybackHapticsEnabledChange,
                )
                SettingsCategory.Interface -> SettingsInterfaceContent(
                    dynamicArtworkEnabled = dynamicArtworkEnabled,
                    compactModeEnabled = compactModeEnabled,
                    uiDensityScale = uiDensityScale,
                    performanceMode = performanceMode,
                    effectivePerformanceMode = effectivePerformanceMode,
                    appLanguage = appLanguage,
                    onDynamicArtworkEnabledChange = onDynamicArtworkEnabledChange,
                    onCompactModeEnabledChange = onCompactModeEnabledChange,
                    onUiDensityScaleChange = onUiDensityScaleChange,
                    onPerformanceModeChange = onPerformanceModeChange,
                    onAppLanguageChange = onAppLanguageChange,
                )
                SettingsCategory.Playback -> SettingsPlaybackContent(
                    subNav = subNav,
                    playbackHapticsEnabled = playbackHapticsEnabled,
                    effectivePerformanceMode = effectivePerformanceMode,
                    onlineLyricsEnabled = onlineLyricsEnabled,
                    lockScreenLyricsEnabled = lockScreenLyricsEnabled,
                    lyricsOptions = lyricsOptions,
                    onLyricsOptionsChange = onLyricsOptionsChange,
                    onOpenLyricsInterface = onOpenLyricsInterface,
                    floatingLyrics = floatingLyrics,
                    floatingLyricsPermissionGranted = floatingLyricsPermissionGranted,
                    usbExclusiveEnabled = usbExclusiveEnabled,
                    usbBitPerfectEnabled = usbBitPerfectEnabled,
                    shuffleOptions = shuffleOptions,
                    onShuffleOptionsChange = onShuffleOptionsChange,
                    trackTransitions = trackTransitions,
                    audioFocusEnabled = audioFocusEnabled,
                    onAudioFocusEnabledChange = onAudioFocusEnabledChange,
                    onResetAudioOutput = onResetAudioOutput,
                    audioInterruptionPolicy = audioInterruptionPolicy,
                    sleepTimerFinishTrack = sleepTimerFinishTrack,
                    audioDiagnostics = status.diagnostics,
                    onOpenSystemAudioEffects = onOpenSystemAudioEffects,
                    systemEffectsLocalPlayback = systemEffectsLocalPlayback,
                    stopOnTaskRemoved = stopOnTaskRemoved,
                    onStopOnTaskRemovedChange = onStopOnTaskRemovedChange,
                    onAudioInterruptionPolicyChange = onAudioInterruptionPolicyChange,
                    onSleepTimerFinishTrackChange = onSleepTimerFinishTrackChange,
                    pauseOnAudioDisconnect = pauseOnAudioDisconnect,
                    resumeOnAudioReconnect = resumeOnAudioReconnect,
                    replayGainEnabled = replayGainEnabled,
                    replayGainMode = replayGainMode,
                    replayGainPreampDb = replayGainPreampDb,
                    onPlaybackHapticsEnabledChange = onPlaybackHapticsEnabledChange,
                    onOnlineLyricsEnabledChange = onOnlineLyricsEnabledChange,
                    onLockScreenLyricsEnabledChange = onLockScreenLyricsEnabledChange,
                    onFloatingLyricsChange = onFloatingLyricsChange,
                    onRequestFloatingLyricsPermission = onRequestFloatingLyricsPermission,
                    onTrackTransitionsChange = onTrackTransitionsChange,
                    onPauseOnAudioDisconnectChange = onPauseOnAudioDisconnectChange,
                    onResumeOnAudioReconnectChange = onResumeOnAudioReconnectChange,
                    onReplayGainChange = onReplayGainChange,
                    onReplayGainModeChange = onReplayGainModeChange,
                    notificationPermissionGranted = notificationPermissionGranted,
                    onRequestNotificationPermission = onRequestNotificationPermission,
                )
                SettingsCategory.Usb -> SettingsUsbContent(
                    status = status,
                    usbExclusiveEnabled = usbExclusiveEnabled,
                    usbBitPerfectEnabled = usbBitPerfectEnabled,
                    options = usbOutputOptions,
                    onOptionsChange = onUsbOutputOptionsChange,
                    usbExclusiveAutoRequestOnStartup = usbExclusiveAutoRequestOnStartup,
                    usbExclusiveTestResult = usbExclusiveTestResult,
                    onUsbExclusiveEnabledChange = onUsbExclusiveEnabledChange,
                    onUsbBitPerfectEnabledChange = onUsbBitPerfectEnabledChange,
                    onUsbExclusiveAutoRequestOnStartupChange = onUsbExclusiveAutoRequestOnStartupChange,
                    onTestUsbExclusiveDriver = onTestUsbExclusiveDriver,
                    onOpenSound = onOpenSound,
                    pauseOnDisconnect = pauseOnAudioDisconnect,
                    resumeOnReconnect = resumeOnAudioReconnect,
                    onPauseOnDisconnect = onPauseOnAudioDisconnectChange,
                    onResumeOnReconnect = onResumeOnAudioReconnectChange,
                )
                SettingsCategory.Services -> SettingsServicesContent(
                    subNav = subNav,
                    pcHandoffEnabled = pcHandoffEnabled,
                    lastFmEnabled = lastFmEnabled,
                    lastFmApiKey = lastFmApiKey,
                    lastFmSharedSecret = lastFmSharedSecret,
                    lastFmSessionKey = lastFmSessionKey,
                    lastFmStatusLabel = lastFmStatusLabel,
                    lastFmErrorLabel = lastFmErrorLabel,
                    lastFmWebAuthPending = lastFmWebAuthPending,
                    lastFmApiKeyLocked = lastFmApiKeyLocked,
                    lastFmSharedSecretLocked = lastFmSharedSecretLocked,
                    listenBrainzEnabled = listenBrainzEnabled,
                    listenBrainzToken = listenBrainzToken,
                    listenBrainzStatusLabel = listenBrainzStatusLabel,
                    listenBrainzErrorLabel = listenBrainzErrorLabel,
                    setlistFmApiKey = setlistFmApiKey,
                    setlistFmApiKeyLocked = setlistFmApiKeyLocked,
                    onPcHandoffEnabledChange = onPcHandoffEnabledChange,
                    onLastFmEnabledChange = onLastFmEnabledChange,
                    onStartLastFmWebAuth = onStartLastFmWebAuth,
                    onCompleteLastFmWebAuth = onCompleteLastFmWebAuth,
                    onDisconnectLastFm = onDisconnectLastFm,
                    onOpenLastFmApiAccounts = onOpenLastFmApiAccounts,
                    onListenBrainzEnabledChange = onListenBrainzEnabledChange,
                    onSaveListenBrainzToken = onSaveListenBrainzToken,
                    onDisconnectListenBrainz = onDisconnectListenBrainz,
                    onSaveSetlistFmApiKey = onSaveSetlistFmApiKey,
                )
                SettingsCategory.Library -> SettingsLibraryContent(
                    subNav = subNav,
                    isActive = isActive,
                    isScanning = libraryScanning,
                    onLoadHealth = onLoadLibraryHealth,
                    onLoadAudioProfile = onLoadLibraryAudioProfile,
                    onInspectLyrics = onInspectLibraryLyrics,
                    trackCount = trackCount,
                    albumCount = albumCount,
                    artistCount = artistCount,
                    durationMs = libraryDurationMs,
                    localSizeBytes = librarySizeBytes,
                    trackAudioInfoTagsVisible = trackAudioInfoTagsVisible,
                    watchedFolderRescanEnabled = watchedFolderRescanEnabled,
                    onTrackAudioInfoTagsVisibleChange = onTrackAudioInfoTagsVisibleChange,
                    onWatchedFolderRescanEnabledChange = onWatchedFolderRescanEnabledChange,
                    onOpenLibrary = onOpenLibrary,
                    onOpenLibraryRepair = onOpenLibraryRepair,
                    onClearLocalLibraryIndex = onClearLocalLibraryIndex,
                    onCleanupLocalLibrary = onCleanupLocalLibrary,
                )
                SettingsCategory.About -> SettingsAboutContent(
                    appVersionLabel = appVersionLabel,
                    updateContent = updateContent,
                    errorLogCount = errorLogCount,
                    onOpenErrorLog = onOpenErrorLog,
                    backupNotice = backupNotice,
                    onExportBackup = onExportBackup,
                    onImportBackup = onImportBackup,
                )
        }
    }
}
