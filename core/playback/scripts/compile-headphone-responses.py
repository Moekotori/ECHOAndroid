"""Generate fixed +/-20, 30, 45 degree stereo responses from pinned SADIE data.

Data only; no OpenAL engine code. Run manually with Python 3; no build downloads.
"""
import hashlib
import math
from pathlib import Path
import struct
import urllib.request

REV = 'b7463649fd73188146e3b1467a91e7f0926a6d04'
URL = f'https://raw.githubusercontent.com/kcat/openal-soft/{REV}/hrtf/Default%20HRTF.mhr'
source = urllib.request.urlopen(URL, timeout=30).read()
assert hashlib.sha256(source).hexdigest() == '40ed10f203488fdeca5f873bfd64f6fae232f4f7412ba07ae5e501ad882adf8c'
assert source[:8] == b'MinPHR03'
assert struct.unpack_from('<IBBBHB', source, 8) == (48000, 0, 64, 1, 1200, 13)
counts = source[18:31]
offset = sum(counts[:6])
count = counts[6]
delays = 31 + sum(counts) * 64 * 3
banks = []
for angle in (20, 30, 45):
    responses = []
    # Input left/right virtual speaker; for each, output left/right ear.
    for speaker in (-angle, angle):
        for ear in (0, 1):
            azimuth = ((speaker if ear == 0 else -speaker) % 360) * count / 360
            first = math.floor(azimuth)
            fraction = azimuth - first
            indices = (offset + first, offset + (first + 1) % count)
            response = [0.0] * 128
            delay = (source[delays + indices[0]] * (1-fraction) + source[delays + indices[1]] * fraction) / 4
            # Shared 16-sample guard and a bounded fractional-delay FIR.
            shift = 16 + delay
            integer = math.floor(shift)
            part = shift - integer
            weights = []
            for k in range(-8, 9):
                x = k - part
                weights.append((1 if abs(x) < 1e-12 else math.sin(math.pi*x)/(math.pi*x)) * (0.5+0.5*math.cos(math.pi*k/9)))
            norm = sum(weights)
            for tap in range(64):
                values = [int.from_bytes(source[31+(i*64+tap)*3:34+(i*64+tap)*3], 'little', signed=True)/8388608 for i in indices]
                value = values[0]*(1-fraction) + values[1]*fraction
                for k, weight in enumerate(weights):
                    response[tap + integer + k - 8] += value * weight / norm
            responses.append(response)
    # Leave conservative peak headroom for summing the two virtual speakers.
    bound = max(sum(abs(x) for x in responses[0]+responses[2]), sum(abs(x) for x in responses[1]+responses[3]))
    banks.append([v * min(0.5, 0.9/bound) for response in responses for v in response])
target = Path(__file__).resolve().parents[1] / 'src/main/java/app/echo/android/playback/EchoHrtfResponses.kt'
lines = ['package app.echo.android.playback', '', '// Generated by scripts/compile-headphone-responses.py. SADIE II / Apache-2.0.', '// See third_party/licenses/sadie-hrtf-NOTICE.txt. Fixed 48 kHz, four 128-tap FIRs per profile.', 'internal object EchoHrtfResponses {', '    val banks: Array<FloatArray> = arrayOf(']
for bank in banks:
    lines.append('        floatArrayOf(')
    for i in range(0, len(bank), 8):
        lines.append('            ' + ', '.join(f'{v:.9e}f' for v in bank[i:i+8]) + ',')
    lines.append('        ),')
lines.extend(['    )', '}', ''])
target.write_text('\n'.join(lines), encoding='utf-8')
license_dir = Path(__file__).resolve().parents[1] / 'third_party/licenses'
license_dir.mkdir(parents=True, exist_ok=True)
license_bytes = urllib.request.urlopen(f'https://raw.githubusercontent.com/kcat/openal-soft/{REV}/LICENSE.Apache-2.0.txt', timeout=30).read()
assert hashlib.sha256(license_bytes).hexdigest() == 'cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30'
(license_dir / 'sadie-hrtf-LICENSE.txt').write_bytes(license_bytes)
(license_dir / 'sadie-hrtf-NOTICE.txt').write_text(f'''SADIE II derived HRTF data, University of York.
https://www.york.ac.uk/sadie-project/database.html
OpenAL Soft Default HRTF.mhr, revision {REV}
{URL}
Source SHA-256: 40ed10f203488fdeca5f873bfd64f6fae232f4f7412ba07ae5e501ad882adf8c
Apache License 2.0; see sadie-hrtf-LICENSE.txt.
ECHO Android modifications: extract horizontal +/-20, 30, 45 degree speaker
responses at 1.2 m; reconstruct fractional delays, add a common 16-sample
guard, normalize summing headroom, and retain four 128-tap FIRs per profile.
No OpenAL playback engine is included. These are generic measured responses,
not individual ear measurements or guaranteed externalization.
''', encoding='utf-8')
print(target)
