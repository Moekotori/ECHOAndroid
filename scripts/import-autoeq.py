"""Build the bundled, deterministic AutoEQ catalog from an upstream checkout.

Usage: python scripts/import-autoeq.py --checkout /path/to/AutoEq
Requires a clean checkout at a pinned upstream revision. Only numerical PEQ data
and the upstream MIT license are imported; no application code is downloaded.
"""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path
import re
import subprocess


def build(checkout: Path, destination: Path):
    revision = subprocess.check_output(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True).strip()
    if subprocess.check_output(["git", "-C", str(checkout), "status", "--porcelain"], text=True).strip():
        raise ValueError("Use a clean upstream checkout for reproducible data")
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Invalid upstream revision")
    filters = re.compile(
        r"Filter \d+: ON (PK|LSC|HSC) Fc ([\d.]+) Hz Gain (-?[\d.]+) dB Q ([\d.]+)")
    rows = []
    for file in sorted((checkout / "results").rglob("* ParametricEQ.txt")):
        relative = file.relative_to(checkout / "results")
        if len(relative.parts) != 4:
            raise ValueError(f"Unsupported result path: {relative}")
        source, measurement_rig, model, _ = relative.parts
        category = measurement_rig
        category = next((value for value in ("in-ear", "over-ear", "earbud") if category.endswith(value)), None)
        if category is None:
            raise ValueError(f"Unknown headphone category: {relative}")
        text = file.read_text(encoding="utf-8-sig")
        preamp = re.search(r"^Preamp: (-?[\d.]+) dB", text, re.M)
        matched = filters.findall(text)
        declared = [line for line in text.splitlines() if line.startswith("Filter ")]
        if preamp is None or not 1 <= len(matched) <= 32 or len(declared) != len(matched):
            raise ValueError(f"Unsupported/incomplete EQ: {relative}")
        if not -24 <= float(preamp[1]) <= 0:
            raise ValueError(f"Unsupported preamp: {relative}")
        for _, frequency, gain, q in matched:
            if not (20 <= float(frequency) <= 20000 and -24 <= float(gain) <= 20 and .1 <= float(q) <= 100):
                raise ValueError(f"Filter exceeds ECHO PEQ limits: {relative}")
        identifier = hashlib.sha256(("results/" + relative.as_posix()).encode()).hexdigest()[:20]
        encode = lambda value: base64.b64encode(value.encode()).decode()
        encoded_filters = ";".join(
            f"{dict(PK='P', LSC='L', HSC='H')[kind]},{frequency},{gain},{q}"
            for kind, frequency, gain, q in matched)
        rows.append("\t".join((identifier, category, encode(source), encode(model), preamp[1], encoded_filters, encode(measurement_rig))))
    if not rows:
        raise ValueError("No AutoEQ profiles found")
    raw = (f"# AutoEq Parametric EQ catalog\n# revision={revision}\n# count={len(rows)}\n"
           + "\n".join(rows) + "\n").encode()
    if len(raw) > 4 * 1024 * 1024 or len(rows) > 20000:
        raise ValueError("Catalog exceeds Android reader limits; review limits before updating")
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "catalog-v1.tsv.gz").write_bytes(gzip.compress(raw, compresslevel=9, mtime=0))
    (destination / "LICENSE.txt").write_bytes((checkout / "LICENSE").read_bytes())
    (destination / "NOTICE.txt").write_text(
        f"AutoEq headphone equalization data\nSource: https://github.com/jaakkopasanen/AutoEq\n"
        f"Revision: {revision}\nProfiles: {len(rows)}\nLicense: MIT (LICENSE.txt)\n"
        f"Data SHA-256 (uncompressed): {hashlib.sha256(raw).hexdigest()}\n"
        "Generated by scripts/import-autoeq.py from the upstream results directory.\n",
        encoding="utf-8", newline="\n")
    (destination / "provenance.json").write_text(json.dumps({
        "source": "https://github.com/jaakkopasanen/AutoEq",
        "revision": revision,
        "profiles": len(rows),
        "uncompressedSha256": hashlib.sha256(raw).hexdigest(),
        "input": "clean upstream checkout",
        "license": "MIT",
    }, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Bundled {len(rows)} AutoEQ profiles from {revision}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkout", type=Path, required=True)
    parser.add_argument("--destination", type=Path, default=Path(__file__).resolve().parents[1] / "core/data/src/main/assets/autoeq")
    args = parser.parse_args()
    build(args.checkout.resolve(), args.destination.resolve())
