// Assembles the Jizura engine from a local echosteam checkout into one offline HTML asset.
// Usage: node scripts/jizura/build-engine.mjs <path-to-echosteam>
// Mirrors src/renderer/components/lyrics/jizura/jizuraDocument.ts: same scripts, same order, same CSP.
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

if (!process.argv[2]) throw new Error('usage: node scripts/jizura/build-engine.mjs <path-to-echosteam>');
const pc = resolve(process.argv[2]);
const jizura = join(pc, 'src/renderer/components/lyrics/jizura');
const out = join(dirname(fileURLToPath(import.meta.url)), '../../feature/player/src/main/assets/jizura');

// Keep in step with `scriptUrls` in jizuraDocument.ts (vendor/*.js sorted first, then these).
const extra = [
  'jizuraAfterglowBackdrops', 'jizuraAfterglowBackdropsB', 'jizuraAfterglowLayouts', 'jizuraAfterglowLayoutsB',
  'jizuraAfterglowLayoutsC', 'jizuraAfterglowExits', 'jizuraOriginalDirection', 'jizuraScenePackDrawing',
  'jizuraScenePack', 'jizuraFrameCaches', 'jizuraEffectWindow', 'jizuraBackdropContinuity', 'jizuraLyricTiming',
  'jizuraEchoNoHuge', 'jizuraFrameDriver', 'jizuraFrameWake', 'jizuraMenuShortcut', 'jizuraClock', 'jizuraFrame',
].map(name => `${name}.js`);
const vendor = readdirSync(join(jizura, 'vendor')).filter(name => name.endsWith('.js')).sort().map(name => join('vendor', name));
const scripts = [...vendor, ...extra].map(file => ({ file, text: readFileSync(join(jizura, file), 'utf8') }));

// The looks table is TypeScript data; bundle it with the checkout's own esbuild and evaluate it.
const esbuild = createRequire(join(pc, 'package.json'))('esbuild');
const bundled = esbuild.buildSync({ entryPoints: [join(jizura, 'jizuraLooks.ts')], bundle: true, write: false,
  format: 'cjs', platform: 'neutral', logLevel: 'error' }).outputFiles[0].text;
const sandbox = { module: { exports: {} }, exports: {} };
vm.runInNewContext(bundled, sandbox);
const looks = sandbox.module.exports.jizuraLooks;
if (!Array.isArray(looks) || !looks.length) throw new Error('jizuraLooks did not evaluate');

const safe = value => value.replace(/<\/script/gi, '<\\/script');
const license = readFileSync(join(jizura, 'vendor/LICENSE'), 'utf8').replace(/\*\//g, '* /');
// The engine talks to `parent`; at top level that is `window`. Route its outgoing messages to Android and
// let the host deliver incoming ones as window message events with `source === window`.
const shim = `(() => {
  const host = window.EchoJizuraHost;
  window.postMessage = message => { try { host.post(JSON.stringify(message)); } catch (_) {} };
  window.__echoDeliver = json => {
    let data; try { data = JSON.parse(json); } catch (_) { return; }
    window.dispatchEvent(new MessageEvent('message', { data, source: window }));
  };
})();`;
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src 'none'; connect-src 'none'; base-uri 'none'; form-action 'none'">
<style>html,body{margin:0;width:100%;height:100%;overflow:hidden;color-scheme:dark;background:#000}body{position:fixed;inset:0;display:flex;align-items:center;justify-content:center}canvas{display:block}</style>
</head><body><canvas aria-label="JIZURA"></canvas>
<script>/* ${license} */
${shim}
addEventListener('error', () => parent.postMessage({ type: 'echo:jizura:error' }, '*'), true);
const ECHO_JIZURA_LOOKS = ${safe(JSON.stringify(looks))};</script>
${scripts.map(({ text }) => `<script>${safe(text)}</script>`).join('\n')}</body></html>`;

const revision = execFileSync('git', ['-C', pc, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const sources = JSON.parse(readFileSync(join(jizura, 'vendor/sources.json'), 'utf8'));
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'engine.html'), html);
writeFileSync(join(out, 'SOURCE.md'), `# Jizura engine asset

\`engine.html\` is generated by \`scripts/jizura/build-engine.mjs\`; do not edit it by hand.

- ECHOSteam revision: \`${revision}\` (https://github.com/moekotori/echosteam)
- Upstream JIZURA ${sources.version}: ${sources.repository} @ \`${sources.commit}\`
- Scripts: ${scripts.length}; looks: ${looks.length}
- License: MIT, Copyright (c) 2026 hakoniwa. The full text is embedded at the top of \`engine.html\`.
- Only the shim at the top adapts the engine to Android (\`window.postMessage\` -> \`EchoJizuraHost.post\`); engine files are unmodified.
`);
console.log(`engine.html ${(html.length / 1024 / 1024).toFixed(2)} MiB, ${scripts.length} scripts, ${looks.length} looks @ ${revision}`);
